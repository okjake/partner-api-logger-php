// Generates src/RedactPiiFoldTable.php: the per-character fold the phone rule
// matches on, as `@partner-api/logger`'s `foldForMatching` computes it
// (packages/logger/src/redact-pii.ts), for every character whose fold can
// change what a rule sees — an empty fold (format characters) or one holding
// an ASCII character (Unicode spaces, dashes, @-confusables, and the NFKC
// compatibility forms of digits, letters and punctuation). FLT-1191.
//
// PHP has no NFKC without ext-intl, and the SDK requires no extension beyond
// core, so the fold is a table rather than a call. It reads the rule sources
// from the TypeScript module itself, so a change there is a regeneration here.
//
//   node --experimental-strip-types packages/logger-php/scripts/generate-redact-pii-fold-table.mjs
//   node --experimental-strip-types packages/logger-php/scripts/generate-redact-pii-fold-table.mjs --check
//
// Fullwidth ASCII (U+FF01-U+FF5E) is left out: RedactPii folds that block
// arithmetically, as the TypeScript does.

import { mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));

// The logger package is CommonJS, so Node would load its .ts source as CJS;
// a .mts copy loads it as the ES module it is written as.
const scratch = mkdtempSync(join(tmpdir(), 'redact-pii-fold-'));
const source = join(scratch, 'redact-pii.mts');
writeFileSync(
  source,
  readFileSync(join(here, '..', '..', 'logger', 'src', 'redact-pii.ts'))
);
const { PLATFORM_RULE_SOURCES: rules } = await import(
  pathToFileURL(source).href
);
rmSync(scratch, { recursive: true });

const INVISIBLE = new RegExp(rules.invisible, 'u');
const SPACE_SEPARATOR = new RegExp(rules.spaceSeparator, 'u');
const DASH = new RegExp(rules.dash, 'u');
const AT_CONFUSABLES = new Set(rules.atConfusables);

/** `foldForMatching`'s per-character branch, in its order. */
function fold(character) {
  if (INVISIBLE.test(character)) return '';
  if (AT_CONFUSABLES.has(character)) return '@';
  if (SPACE_SEPARATOR.test(character)) return ' ';
  if (DASH.test(character)) return '-';
  return character.normalize('NFKC');
}

function phpString(text) {
  let out = '';
  for (const character of text) {
    const code = character.codePointAt(0);
    if (code >= 0x20 && code < 0x7f) {
      out += '"\\$'.includes(character) ? `\\${character}` : character;
    } else {
      out += `\\u{${code.toString(16).toUpperCase().padStart(4, '0')}}`;
    }
  }
  return `"${out}"`;
}

const entries = [];
for (let code = 0x80; code <= 0x10ffff; code++) {
  if (code >= 0xd800 && code <= 0xdfff) continue;
  if (code >= 0xff01 && code <= 0xff5e) continue;
  const character = String.fromCodePoint(code);
  const folded = fold(character);
  if (folded === character) continue;
  if (folded !== '' && !/[\x00-\x7f]/.test(folded)) continue;
  entries.push(`        ${phpString(character)} => ${phpString(folded)},`);
}

const php = `<?php

declare(strict_types=1);

namespace PartnerApi\\Logger;

/**
 * GENERATED by scripts/generate-redact-pii-fold-table.mjs — do not edit.
 * Node ${process.versions.node}, Unicode ${process.versions.unicode}.
 *
 * The characters \`RedactPii\`'s phone rule folds before matching, and what each
 * folds to: every character whose fold in \`@partner-api/logger\`'s
 * \`foldForMatching\` is empty or holds an ASCII character. A character whose
 * fold is non-ASCII only is matched as written: every rule reads ASCII, so no
 * match can change, though the phone rule's 15-character context window can
 * span a little more or less text than the TypeScript's around it.
 *
 * @internal
 */
final class RedactPiiFoldTable
{
    /** @var array<string, string> */
    public const FOLD = [
${entries.join('\n')}
    ];
}
`;

const target = join(here, '..', 'src', 'RedactPiiFoldTable.php');
if (process.argv.includes('--check')) {
  const current = readFileSync(target, 'utf8').replace(/^ \* Node .*$/m, '');
  if (current !== php.replace(/^ \* Node .*$/m, '')) {
    console.error(`${target} is stale: rerun this script without --check.`);
    process.exit(1);
  }
  console.log(`${target} is current (${entries.length} characters).`);
} else {
  writeFileSync(target, php);
  console.log(`wrote ${entries.length} characters to ${target}`);
}
